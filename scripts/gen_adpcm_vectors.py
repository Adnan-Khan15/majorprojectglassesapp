#!/usr/bin/env python3
"""Generates IMA ADPCM golden vectors from an independent Python reference.

Writes the SAME vectors to:
  esp32-firmware/test/test_core/adpcm_golden.h            (C, for `pio test -e native`)
  android-app/app/src/test/resources/adpcm_golden.json    (Kotlin unit tests)

Both firmware and app implementations must reproduce these bytes exactly, which
proves they agree with each other on the wire without one being copied from the
other. Re-run only if the test signal or block layout changes:
  python3 scripts/gen_adpcm_vectors.py
"""
import json
import math
import os

STEP = [7, 8, 9, 10, 11, 12, 13, 14, 16, 17, 19, 21, 23, 25, 28, 31, 34, 37, 41, 45, 50, 55, 60, 66, 73,
        80, 88, 97, 107, 118, 130, 143, 157, 173, 190, 209, 230, 253, 279, 307, 337, 371, 408, 449, 494,
        544, 598, 658, 724, 796, 876, 963, 1060, 1166, 1282, 1411, 1552, 1707, 1878, 2066, 2272, 2499,
        2749, 3024, 3327, 3660, 4026, 4428, 4871, 5358, 5894, 6484, 7132, 7845, 8630, 9493, 10442, 11487,
        12635, 13899, 15289, 16818, 18500, 20350, 22385, 24623, 27086, 29794, 32767]
INDEX = [-1, -1, -1, -1, 2, 4, 6, 8, -1, -1, -1, -1, 2, 4, 6, 8]

SAMPLES_PER_BLOCK = 400  # = one BLE audio frame (25 ms at 16 kHz)


class State:
    def __init__(self, pred=0, idx=0):
        self.pred, self.idx = pred, idx

    def apply(self, nib):
        s = STEP[self.idx]
        diff = s >> 3
        if nib & 4: diff += s
        if nib & 2: diff += s >> 1
        if nib & 1: diff += s >> 2
        p = self.pred - diff if nib & 8 else self.pred + diff
        self.pred = max(-32768, min(32767, p))
        self.idx = max(0, min(88, self.idx + INDEX[nib]))
        return self.pred

    def encode(self, x):
        s = STEP[self.idx]
        d = x - self.pred
        nib = 0
        if d < 0:
            nib, d = 8, -d
        if d >= s: nib |= 4; d -= s
        s >>= 1
        if d >= s: nib |= 2; d -= s
        s >>= 1
        if d >= s: nib |= 1
        self.apply(nib)
        return nib


def signal():
    """Deterministic test signal covering the codec's corners: sweep, loud square
    (clipping), silence, and pseudo-random noise."""
    out = []
    for i in range(800):  # chirp with rising amplitude
        f = 200 + 3000 * i / 800
        out.append(int(20000 * (i / 800) * math.sin(2 * math.pi * f * i / 16000)))
    for i in range(400):  # full-scale square
        out.append(32767 if (i // 20) % 2 == 0 else -32768)
    out += [0] * 400
    seed = 12345
    for _ in range(400):  # LCG noise
        seed = (seed * 1103515245 + 12345) & 0x7FFFFFFF
        out.append((seed >> 8) % 20001 - 10000)
    return out


def main():
    pcm = signal()
    assert len(pcm) % SAMPLES_PER_BLOCK == 0
    enc_state = State()
    blocks = []
    for b in range(0, len(pcm), SAMPLES_PER_BLOCK):
        start = (enc_state.pred, enc_state.idx)
        chunk = pcm[b:b + SAMPLES_PER_BLOCK]
        data = []
        for i in range(0, len(chunk), 2):
            lo = enc_state.encode(chunk[i])
            hi = enc_state.encode(chunk[i + 1])
            data.append(lo | (hi << 4))
        # decode independently from the block's start state (what a receiver does)
        dec_state = State(*start)
        decoded = []
        for byte in data:
            decoded.append(dec_state.apply(byte & 15))
            decoded.append(dec_state.apply(byte >> 4))
        assert (dec_state.pred, dec_state.idx) == (enc_state.pred, enc_state.idx)
        blocks.append({"start_predictor": start[0], "start_index": start[1], "pcm": chunk,
                       "adpcm": data, "decoded": decoded})

    root = os.path.join(os.path.dirname(__file__), "..")
    json_path = os.path.join(root, "android-app/app/src/test/resources/adpcm_golden.json")
    os.makedirs(os.path.dirname(json_path), exist_ok=True)
    with open(json_path, "w") as f:
        json.dump({"samples_per_block": SAMPLES_PER_BLOCK, "blocks": blocks}, f)

    h_path = os.path.join(root, "esp32-firmware/test/test_core/adpcm_golden.h")
    with open(h_path, "w") as f:
        f.write("// GENERATED by scripts/gen_adpcm_vectors.py - do not edit.\n#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define GOLDEN_BLOCKS {len(blocks)}\n#define GOLDEN_SPB {SAMPLES_PER_BLOCK}\n\n")
        f.write("static const int16_t GOLDEN_START_PRED[] = {%s};\n" % ", ".join(str(b["start_predictor"]) for b in blocks))
        f.write("static const uint8_t GOLDEN_START_INDEX[] = {%s};\n" % ", ".join(str(b["start_index"]) for b in blocks))
        f.write("static const int16_t GOLDEN_PCM[] = {%s};\n" % ", ".join(str(x) for b in blocks for x in b["pcm"]))
        f.write("static const uint8_t GOLDEN_ADPCM[] = {%s};\n" % ", ".join(str(x) for b in blocks for x in b["adpcm"]))
        f.write("static const int16_t GOLDEN_DECODED[] = {%s};\n" % ", ".join(str(x) for b in blocks for x in b["decoded"]))
    print(f"wrote {len(blocks)} blocks to\n  {os.path.normpath(json_path)}\n  {os.path.normpath(h_path)}")


if __name__ == "__main__":
    main()
