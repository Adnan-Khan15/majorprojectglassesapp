#!/usr/bin/env python3
"""Generates the Arduino IDE version of the glasses firmware.

  python3 scripts/make_arduino_sketch.py           # (re)write esp32-firmware/arduino/SmartGlasses/
  python3 scripts/make_arduino_sketch.py --check   # exit 1 if the sketch is out of date

The PlatformIO project in esp32-firmware/ is the source of truth. The Arduino IDE
needs everything in one sketch folder named like its .ino file, so this copies:
  src/main.cpp            -> SmartGlasses.ino
  src/*.cpp, src/*.h      -> same names
  include/*.h             -> same names
  lib/glasses_core/src/*  -> same names (.c / .h)
Never edit the sketch folder by hand: edit the originals and re-run this script
(scripts/tests/test_arduino_sketch.py fails if you forget).
"""
import os
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), ".."))
FW = os.path.join(ROOT, "esp32-firmware")
OUT = os.path.join(FW, "arduino", "SmartGlasses")
SKETCH = "SmartGlasses.ino"

BANNER = ("// GENERATED by scripts/make_arduino_sketch.py from esp32-firmware/{src}\n"
          "// Do not edit here: edit the original, then re-run the script.\n")

SKETCH_README = """# SmartGlasses: Arduino IDE sketch

Generated from the PlatformIO project in `esp32-firmware/` by `scripts/make_arduino_sketch.py`.
**Don't edit files here**: change the originals in `esp32-firmware/src`, `include` or `lib`, then re-run the script.

## Open and flash with the Arduino IDE (2.x)

1. **Board support:** Tools → Board → Boards Manager → search **esp32** (by Espressif Systems) → install version **2.0.17**.
   Version 3.x will NOT compile: the audio code uses the 2.0.x I2S driver.
2. **Libraries:** Sketch → Include Library → Manage Libraries → install:
   - **NimBLE-Arduino** by h2zero, version **2.3.0 or newer**
   - **VL53L0X** by **Pololu**, version 1.3.1 (not the Adafruit one)
3. **Open** `SmartGlasses.ino` (File → Open). The other files in this folder open as tabs.
4. **Tools menu** (these settings matter):
   | Setting | Value |
   |---|---|
   | Board | **XIAO_ESP32S3** |
   | PSRAM | **OPI PSRAM** (required: photos and the speech buffer live in PSRAM) |
   | USB CDC On Boot | **Enabled** (serial console over USB) |
   | Flash Size | 8MB |
   | Partition Scheme | Default 4MB with spiffs (or the 8MB default) |
   | Core Debug Level | None or Error |
5. Plug in the board (hold **BOOT** while plugging in if it isn't detected), pick its port, click **Upload**.
6. Tools → Serial Monitor at **115200** baud, line ending "Newline". Type `?` and press Enter for the test commands.

The prebuilt image on the Releases page (`smartglasses-firmware-…-merged.bin`) is the same firmware, if you'd rather not set up the IDE.
"""


def plan():
    """Returns {output file name: (source path relative to esp32-firmware, text)}."""
    files = {}

    def add(rel, out_name):
        with open(os.path.join(FW, rel)) as f:
            files[out_name] = (rel, BANNER.format(src=rel) + f.read())

    for d, exts in (("src", (".cpp", ".h")), ("include", (".h",)), (os.path.join("lib", "glasses_core", "src"), (".c", ".h"))):
        for name in sorted(os.listdir(os.path.join(FW, d))):
            if not name.endswith(exts):
                continue
            rel = os.path.join(d, name)
            out = SKETCH if rel == os.path.join("src", "main.cpp") else name
            if out in files:
                raise SystemExit(f"name clash: {name} exists in two firmware folders")
            add(rel, out)
    files["README.md"] = ("(generated)", SKETCH_README)
    return files


def main():
    check = "--check" in sys.argv
    want = plan()
    have = set(os.listdir(OUT)) if os.path.isdir(OUT) else set()
    stale = [n for n, (_, text) in want.items()
             if not os.path.exists(os.path.join(OUT, n)) or open(os.path.join(OUT, n)).read() != text]
    extra = sorted(have - set(want))
    if check:
        if stale or extra:
            print("Arduino sketch is out of date. Run: python3 scripts/make_arduino_sketch.py")
            for n in stale:
                print("  changed/missing:", n)
            for n in extra:
                print("  no longer generated:", n)
            sys.exit(1)
        print(f"Arduino sketch up to date ({len(want)} files)")
        return
    os.makedirs(OUT, exist_ok=True)
    for n in extra:
        os.remove(os.path.join(OUT, n))
    for n, (_, text) in want.items():
        with open(os.path.join(OUT, n), "w") as f:
            f.write(text)
    print(f"wrote {len(want)} files to {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
